-- Public QR pages may verify an asset and see its valuation summary, but must not read the full inventory row.
drop function if exists public.get_public_asset_qr(text);
create or replace function public.get_public_asset_qr(asset_lookup text)
returns table (
  asset_id text,
  property_no text,
  semi_expandable_no text,
  inventory_type text,
  item_classification text,
  item_brand_model text,
  serial_no text,
  acquisition_date text,
  fund_cluster text,
  unit_measurement text,
  mooe_month text,
  mooe_year numeric,
  status text,
  accountable_person text,
  plantilla_position text,
  school_level text,
  location text,
  date_issue text,
  unit_value numeric,
  total numeric,
  on_hand numeric,
  balance numeric,
  shortage_overage_qty numeric,
  shortage_overage_value numeric,
  remarks text
)
language sql
stable
security definer
set search_path = ''
as $$
  select a.asset_id, a.property_no, a.semi_expandable_no, a.inventory_type,
         a.item_classification, a.item_brand_model, a.serial_no,
         a.acquisition_date, a.fund_cluster, a.unit_measurement,
         a.mooe_month, a.mooe_year, a.status,
         a.accountable_person, a.plantilla_position, a.school_level, a.location, a.date_issue,
         a.unit_value, a.total, a.on_hand, a.balance,
         a.shortage_overage_qty, a.shortage_overage_value, a.remarks
  from public.assets as a
  where a.asset_id = asset_lookup or a.property_no = asset_lookup
  order by case when a.asset_id = asset_lookup then 0 else 1 end
  limit 1;
$$;

revoke all on function public.get_public_asset_qr(text) from public;
grant execute on function public.get_public_asset_qr(text) to anon, authenticated;

-- Public QR pages can read only the photo paths for the requested asset.
-- Asset photo metadata remains unavailable through direct anonymous table reads.
drop function if exists public.get_public_asset_images(text);
create or replace function public.get_public_asset_images(asset_lookup text)
returns table (
  file_path text,
  is_primary boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select image.file_path, image.is_primary
  from public.asset_images as image
  join public.assets as asset on asset.asset_id = image.asset_id
  where asset.asset_id = asset_lookup
     or (asset.property_no = asset_lookup and not exists (
       select 1 from public.assets as exact_asset where exact_asset.asset_id = asset_lookup
     ))
  order by image.is_primary desc, image.created_at asc;
$$;

revoke all on function public.get_public_asset_images(text) from public;
grant execute on function public.get_public_asset_images(text) to anon, authenticated;
