-- Inventory Custodian Slip (ICS) document records.
-- Keep these separate from assets: a slip is a historical custody document and can contain multiple assets.
create table if not exists public.ics_slips (
  id bigint generated by default as identity primary key,
  ics_no text not null unique,
  entity_name text not null,
  fund_cluster text,
  received_from_name text,
  received_from_position text,
  received_from_date date,
  received_by_name text,
  received_by_position text,
  received_by_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ics_slip_items (
  id bigint generated by default as identity primary key,
  ics_slip_id bigint not null references public.ics_slips(id) on delete cascade,
  line_no integer not null check (line_no > 0),
  asset_id bigint references public.assets(id) on delete set null,
  inventory_item_no text,
  description_snapshot text not null,
  quantity numeric(14, 2) not null check (quantity > 0),
  unit text,
  unit_cost numeric(14, 2) not null check (unit_cost >= 0),
  total_cost numeric(14, 2) not null check (total_cost >= 0),
  estimated_useful_life text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (ics_slip_id, line_no)
);

create index if not exists ics_slip_items_ics_slip_id_idx
  on public.ics_slip_items (ics_slip_id);

create index if not exists ics_slip_items_asset_id_idx
  on public.ics_slip_items (asset_id);

create or replace function public.set_ics_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_ics_slips_updated_at on public.ics_slips;
create trigger set_ics_slips_updated_at
  before update on public.ics_slips
  for each row execute function public.set_ics_updated_at();

drop trigger if exists set_ics_slip_items_updated_at on public.ics_slip_items;
create trigger set_ics_slip_items_updated_at
  before update on public.ics_slip_items
  for each row execute function public.set_ics_updated_at();

