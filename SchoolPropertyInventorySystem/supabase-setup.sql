update public.assets as a
set plantilla_position = (
  select nullif(trim(st.plantilla_position), '')
  from public.school_teacher as st
  where lower(trim(a.accountable_person)) = lower(trim(st.teacher_name))
    and nullif(trim(st.plantilla_position), '') is not null
  order by st.id desc
  limit 1
)
where nullif(trim(a.plantilla_position), '') is null
  and exists (
    select 1
    from public.school_teacher as st
    where lower(trim(a.accountable_person)) = lower(trim(st.teacher_name))
      and nullif(trim(st.plantilla_position), '') is not null
  );


